// Retrofit.create() turns the @POST annotations of UserService/BoxesService into a dynamic proxy
// at run time. Kotlin/Wasm has no proxies or annotation reflection, so the same step happens at
// build time: this task reads both interfaces and writes classes that implement them.
val serviceProxies = tasks.register("serviceProxies") {
    val services = listOf("user/UserService.kt", "boxes/BoxesService.kt")
        .map { file("../../app/src/main/java/com/diches/dichboxmobile/api/$it") }
    val out = layout.buildDirectory.dir("serviceProxies")
    inputs.files(services)
    outputs.dir(out)
    doLast {
        val route = Regex("""@POST\("([^"]+)"\)\s*suspend fun (\w+)\(""")
        val iface = Regex("""package ([\w.]+)[\s\S]*?interface (\w+)""")
        val impls = services.map { src ->
            val text = src.readText()
            val (pkg, name) = iface.find(text)!!.destructured
            val methods = route.findAll(text).joinToString("\n") { m ->
                val (path, fn) = m.destructured
                "    override suspend fun $fn(requestBody: okhttp3.RequestBody) = retrofit.post(\"$path\", requestBody)"
            }
            Triple(pkg, name, "private class ${name}Proxy(private val retrofit: retrofit2.Retrofit) : $pkg.$name {\n$methods\n}\n")
        }
        val factory = impls.joinToString("\n") { (pkg, name, _) -> "    $pkg.$name::class -> ${name}Proxy(retrofit)" }
        val dir = out.get().asFile.resolve("showcase/platform")
        dir.mkdirs()
        dir.resolve("Services.kt").writeText(
            "// Generated by the serviceProxies task from the app's Retrofit service interfaces.\n" +
            "package showcase.platform\n\n" + impls.joinToString("\n") { it.third } +
            "\ninternal fun createService(kclass: kotlin.reflect.KClass<*>, retrofit: retrofit2.Retrofit): Any = when (kclass) {\n" +
            factory + "\n    else -> error(\"No service for \$kclass\")\n}\n"
        )
    }
}

// Gson maps JSON onto the app's data classes by reflection, which Kotlin/Wasm doesn't have.
// This task reads UserContainer.kt and BoxesContainer.kt and writes the equivalent mapping
// as plain code: every data class to and from a JsonElement, field by field, with Gson's
// habits (null fields left out; a missing field gets 0, false, or an empty value).
val containerCodec = tasks.register("containerCodec") {
    val sources = listOf("UserContainer.kt", "BoxesContainer.kt")
        .map { file("../../app/src/main/java/com/diches/dichboxmobile/datatypes/$it") }
    val out = layout.buildDirectory.dir("containerCodec")
    inputs.files(sources)
    outputs.dir(out)
    doLast {
        val cls = Regex("""data class (\w+)\(([^)]*)\)""")
        val nest = Regex("""data class (\w+)\([^)]*\)\s*:\s*\w+\(\)\s*\{\s*data class (\w+)""")
        val field = Regex("""va[lr] (\w+): ([\w.<>]+)(\?)?""")
        val prims = setOf("String", "Int", "Boolean")
        val encode = StringBuilder()
        val decode = StringBuilder()
        val keys = StringBuilder()
        for (src in sources) {
            val outer = src.nameWithoutExtension
            val text = src.readText()
            val parentOf = nest.findAll(text).associate { it.groupValues[2] to it.groupValues[1] }
            for (m in cls.findAll(text)) {
                val name = m.groupValues[1]
                val qualified = outer + "." + (parentOf[name]?.let { "$it." } ?: "") + name
                val key = "$outer.$name"
                keys.append("    $qualified::class to \"$key\",\n")
                val enc = mutableListOf<String>()
                val dec = mutableListOf<String>()
                for (f in field.findAll(m.groupValues[2])) {
                    val (fname, type, q) = f.destructured
                    val nullable = q.isNotEmpty()
                    val inner = type.removePrefix("List<").removeSuffix(">")
                    val isList = type.startsWith("List<")
                    val ref = "\"$outer.$inner\""
                    val one = if (inner in prims) "JsonPrimitive(it)" else "gsonEncode(it)"
                    val value = if (isList) "JsonArray(it.map { $one })" else one
                    enc += "v.$fname" + (if (nullable) "?" else "") + ".let { put(\"$fname\", $value) }"
                    val suffix = if (nullable) "N" else ""
                    dec += "$fname = " + when {
                        isList && inner in prims -> "list$suffix(o, \"$fname\") { ${inner.lowercase()}Of(it) }"
                        isList -> "list$suffix(o, \"$fname\") { gsonDecode(it, $ref) as $outer.${parentOf[inner]?.let { "$it." } ?: ""}$inner }"
                        inner in prims -> "${inner.lowercase()}$suffix(o, \"$fname\")"
                        else -> "obj$suffix(o, \"$fname\", $ref) as $outer.$inner" + (if (nullable) "?" else "")
                    }
                }
                encode.append("    is $qualified -> buildJsonObject {\n" + enc.joinToString("") { "        $it\n" } + "    }\n")
                decode.append("    \"$key\" -> $qualified(\n" + dec.joinToString("") { "        $it,\n" } + "    )\n")
            }
        }
        val dir = out.get().asFile.resolve("showcase/platform")
        dir.mkdirs()
        dir.resolve("ContainerCodec.kt").writeText(
            "// Generated by the containerCodec task from the app's data classes.\n" +
            "package showcase.platform\n\n" +
            "import com.diches.dichboxmobile.datatypes.BoxesContainer\n" +
            "import com.diches.dichboxmobile.datatypes.UserContainer\n" +
            "import kotlinx.serialization.json.*\n\n" +
            "internal val containerKeys: Map<kotlin.reflect.KClass<*>, String> = mapOf(\n$keys)\n\n" +
            "internal fun gsonEncode(v: Any): JsonElement = when (v) {\n$encode    else -> error(\"Not a container: \" + v)\n}\n\n" +
            "internal fun gsonDecode(e: JsonElement, key: String): Any {\n    val o = e as? JsonObject ?: JsonObject(emptyMap())\n    return when (key) {\n" +
            decode.toString().prependIndent("    ") + "        else -> error(\"Unknown container \" + key)\n    }\n}\n"
        )
    }
}

kotlin {
    @OptIn(org.jetbrains.kotlin.gradle.ExperimentalWasmDsl::class)
    wasmJs {
        outputModuleName.set("dichbox")
        browser()
        binaries.executable()
    }
    sourceSets {
        val wasmJsMain by getting {
            kotlin.srcDir(appSources)
            kotlin.srcDir(serviceProxies)
            kotlin.srcDir(containerCodec)
            dependencies {
                implementation("org.jetbrains.kotlinx:kotlinx-serialization-json:1.9.0")
            }
        }
    }
}

